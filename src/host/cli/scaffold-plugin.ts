/**
 * The generated output must match the canonical skeleton exactly, otherwise
 * the scaffold immediately creates a second source of truth:
 * ```
 * plugins/<dir>/
 *   package.json     type: module + esbuild build (output lands in dist/)
 *   tsconfig.json    exactly one paths entry (no rem2-kernel/* wildcard)
 *   plugin.json      entry: dist/index.js (single canonical form)
 *   src/index.ts     export default definePlugin({...}, (ctx) => ({...}))
 * ```
 */

import { mkdir, writeFile, access } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { KERNEL_VERSION } from '../../kernel/version.js'

export interface ScaffoldOptions {
  pluginId: string
  name?: string
  dir?: string
  projectRoot?: string
}

export interface ScaffoldResult {
  pluginDir: string
  files: string[]
}

export function buildManifest(
  pluginId: string,
  name: string,
): Record<string, unknown> {
  const shortName = pluginId.split('.').slice(-1)[0] ?? pluginId
  return {
    id: pluginId,
    name,
    version: '0.1.0',
    // Single canonical form: the build artifact; dev and prod are identical.
    entry: 'dist/index.js',
    dependencies: {},
    optionalDependencies: {},
    // What I provide: statically declared extension-point contributions.
    contributes: [{ point: 'command.provide', id: shortName }],
    // What I need: capability declarations.
    requires: ['command.provide'],
    compatibility: {
      minKernel: `^${KERNEL_VERSION.split('.').slice(0, 2).join('.')}.0`,
      contractVersion: '1',
    },
    author: 'rem2-team',
    description: `${name} plugin (generated by rem2 CLI)`,
    tags: ['generated'],
  }
}

export function buildPackageJson(dirName: string): string {
  const pkg = {
    name: `@rem2/plugin-${dirName}`,
    version: '0.1.0',
    private: true,
    type: 'module',
    description: 'rem2 plugin (generated by CLI)',
    main: './dist/index.js',
    exports: {
      '.': './dist/index.js',
    },
    scripts: {
      build:
        'esbuild src/index.ts --bundle --format=esm --platform=node --target=node20 --outfile=dist/index.js',
      typecheck: 'tsc --noEmit -p tsconfig.json',
    },
  }
  return `${JSON.stringify(pkg, null, 2)}\n`
}

export function buildTsConfig(): string {
  const cfg = {
    compilerOptions: {
      target: 'ESNext',
      lib: ['ESNext'],
      module: 'NodeNext',
      moduleResolution: 'NodeNext',
      strict: true,
      // Emission is handled by esbuild; paths only affect types, and the
      // output contains no rem2-kernel (it is inlined by bundling).
      noEmit: true,
      skipLibCheck: true,
      resolveJsonModule: true,
      isolatedModules: true,
      types: ['node'],
      baseUrl: '.',
      // Exactly one entry: makes "plugins may only reference the kernel via
      // its public export" a type-level constraint.
      paths: { 'rem2-kernel': ['../../src/kernel/index.ts'] },
    },
    include: ['src/**/*.ts'],
  }
  return `${JSON.stringify(cfg, null, 2)}\n`
}

export function buildPluginSource(pluginId: string, name: string): string {
  const shortName = pluginId.split('.').slice(-1)[0] ?? pluginId
  return `/**
 * ${name} plugin (generated by rem2 CLI).
 *
 * Reference the kernel only through its public export \`rem2-kernel\`: types + tokens + \`definePlugin\`.
 * Capability contributions go through \`ctx.extensions\` (the extension point registry); no Svelte components are provided.
 */

import { definePlugin } from 'rem2-kernel'
import type { PluginContext } from 'rem2-kernel'

export default definePlugin(
  { id: '${pluginId}', name: '${name}', version: '0.1.0' },
  (ctx: PluginContext) => {
    const unsubs: Array<() => void> = []

    return {
      async onConfigure(): Promise<void> {
        ctx.log.info('${pluginId} configured')
        // Contribute to an extension point (example): attach an implementation to a declared extension point.
        // ctx.extensions.contribute('command.provide', {
        //   contributionId: '${shortName}',
        //   impl: async (args) => ({ ok: true, echo: args }),
        // });
        void unsubs
      },

      async onStart(): Promise<void> {
        ctx.log.info('${pluginId} started')
      },

      async onStop(_ctx: PluginContext, reason: string): Promise<void> {
        for (const u of unsubs) u()
        unsubs.length = 0
        ctx.log.info(\`${pluginId} stopped (reason: \${reason})\`);
      },
    };
  },
);
`
}

export async function scaffoldPlugin(
  opts: ScaffoldOptions,
): Promise<ScaffoldResult> {
  const baseDir = opts.dir
    ? path.resolve(opts.projectRoot ?? process.cwd(), opts.dir)
    : path.resolve(opts.projectRoot ?? process.cwd(), 'plugins')
  const dirName = opts.pluginId.replace(/[^a-z0-9._-]/gi, '_')
  const pluginDir = path.join(baseDir, dirName)

  if (await pathExists(pluginDir)) {
    throw new Error(`Target directory already exists: ${pluginDir}`)
  }

  await mkdir(path.join(pluginDir, 'src'), { recursive: true })

  const name = opts.name ?? opts.pluginId
  const manifestPath = path.join(pluginDir, 'plugin.json')
  const sourcePath = path.join(pluginDir, 'src', 'index.ts')
  const packagePath = path.join(pluginDir, 'package.json')
  const tsconfigPath = path.join(pluginDir, 'tsconfig.json')

  await writeFile(
    manifestPath,
    `${JSON.stringify(buildManifest(opts.pluginId, name), null, 2)}\n`,
    'utf8',
  )
  await writeFile(sourcePath, buildPluginSource(opts.pluginId, name), 'utf8')
  await writeFile(packagePath, buildPackageJson(dirName), 'utf8')
  await writeFile(tsconfigPath, buildTsConfig(), 'utf8')

  return {
    pluginDir,
    files: [manifestPath, sourcePath, packagePath, tsconfigPath],
  }
}

async function pathExists(p: string): Promise<boolean> {
  try {
    await access(p)
    return true
  } catch {
    return false
  }
}
